package runner

import (
	"fmt"
	"os"
	"path/filepath"
)

// ShimFileName is the file `grunnr cov shim init` writes into a package that
// does not already have a shim. It is a fixed name so a re-run can recognise
// its own work instead of appending a second TestMain the package will not
// compile with.
//
// A package that already carries the pre-rename atlas_shim_test.go keeps it:
// InitDir writes to the file the existing generated TestMain lives in, not to
// this name. Renaming someone's committed file is churn in their repository
// to serve our rename, and getting it wrong leaves the package with two
// TestMain declarations and no build.
const ShimFileName = "grunnr_shim_test.go"

// generatedMarker is how grunnr tells its own file apart from a developer's.
// Anything without it is never overwritten.
const generatedMarker = "Code generated by `grunnr cov shim init`. DO NOT EDIT."

// legacyGeneratedMarker is the same line as written by the binary when it was
// called atlas. It is recognised, never written.
//
// Without it the rename silently breaks every existing user's upgrade: their
// committed shim no longer matches the marker, so Analyze reports the
// TestMain as hand-written and `grunnr cov shim init` refuses the package
// with "already declares TestMain" -- for a file grunnr wrote itself. The
// refusal is the safe branch, which is exactly why it would have been
// believed rather than investigated.
const legacyGeneratedMarker = "Code generated by `atlas cov shim init`. DO NOT EDIT."

// shimTemplate is the whole generated file. It is one line of behaviour and
// four of explanation on purpose: the developer reading this file in a code
// review needs to know that committing it does not change `go test`.
const shimTemplate = `// ` + generatedMarker + `
//
// Per-test coverage collection. This TestMain is inert unless GRUNNR_COV_DIR
// is set, so ` + "`go test`" + ` behaves exactly as it did before; ` + "`grunnr cov run`" + `
// sets it and collects one coverage snapshot per test.

package %s

import (
	"testing"

	atlascov "github.com/sosalejandro/grunnr/packages/coverage/shim"
)

func TestMain(m *testing.M) { atlascov.Run(m) }
`

// Generate renders the shim for a package clause.
func Generate(clause string) []byte {
	return []byte(fmt.Sprintf(shimTemplate, clause))
}

// InitStatus is what InitDir did to one package.
type InitStatus string

const (
	// StatusCreated: the package had no TestMain and now has ours.
	StatusCreated InitStatus = "created"
	// StatusUnchanged: our shim was already there, byte for byte. This is
	// the status a second `shim init` reports for everything.
	StatusUnchanged InitStatus = "unchanged"
	// StatusUpdated: our shim was there but stale, and was refreshed.
	StatusUpdated InitStatus = "updated"
	// StatusSkipped: the package is not ours to touch, or has no tests.
	StatusSkipped InitStatus = "skipped"
)

// InitResult is one package's outcome.
type InitResult struct {
	Dir    string     `json:"dir"`
	Path   string     `json:"path,omitempty"`
	Status InitStatus `json:"status"`
	Reason string     `json:"reason,omitempty"`
}

// InitDir writes (or refreshes) the shim in one package directory.
//
// The two refusals are the point of the verb. A package that already has a
// TestMain keeps it — rewriting someone's process entry point is not
// something a tool gets to do quietly, and the fix is one line they can add
// themselves. A package with no tests gets nothing, because a TestMain there
// would make the go tool build a test binary that has nothing to run.
func InitDir(dir string) (InitResult, error) {
	a, err := Analyze(dir)
	if err != nil {
		return InitResult{}, err
	}
	res := InitResult{Dir: dir}
	if len(a.Tests) == 0 {
		res.Status, res.Reason = StatusSkipped, "package declares no test functions"
		return res, nil
	}
	if a.TestMain != nil && !a.TestMain.Generated {
		res.Status = StatusSkipped
		res.Reason = fmt.Sprintf(
			"%s already declares TestMain; call shim.Run(m) from it to opt in",
			filepath.Base(a.TestMain.File))
		return res, nil
	}

	// An existing generated TestMain keeps its file name even if someone
	// renamed it: writing the canonical name instead would leave the
	// package with two.
	path := filepath.Join(dir, ShimFileName)
	if a.TestMain != nil {
		path = a.TestMain.File
	}
	res.Path = path

	want := Generate(a.Clause)
	if have, err := os.ReadFile(path); err == nil {
		if string(have) == string(want) {
			res.Status = StatusUnchanged
			return res, nil
		}
		res.Status = StatusUpdated
	} else {
		res.Status = StatusCreated
	}
	if err := os.WriteFile(path, want, 0o644); err != nil {
		return InitResult{}, fmt.Errorf("runner: write %s: %w", path, err)
	}
	return res, nil
}
